#!/usr/bin/env python3
"""Bake this mobile build's share pepper, trial bundle and a friend access code.

The mobile app speaks the desktop's shared-access protocol (`src/app/sharekeys.py`)
byte for byte, so it needs the same **pepper**. That pepper is a credential: it
is what makes a code and its password useless outside a Kriko build. It is not
in the repository, and neither is the trial bundle sealed with it.

Run this before a mobile build, from the repository root and with the repository
environment (the app must be importable):

    .venv\\Scripts\\python.exe kriko-mobile\\tools\\make-secrets.py ^
        --shared-home .tmp-276-friend-fixed\\.kriko --password "sent separately"

The keys are read from `--shared-home`'s existing grant when given, otherwise
from this machine's own environment / `~/.kriko/env`. The keys themselves are
never printed and never written in the clear:

    kriko-mobile/src/engine/secrets.ts   pepper + sealed trial + count
    kriko-mobile/.friend-access.txt      the code and password, gitignored
"""

from __future__ import annotations

import argparse
import json
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app import keys, sharekeys  # noqa: E402

MOBILE = ROOT / "kriko-mobile"
SECRETS = MOBILE / "src" / "engine" / "secrets.ts"
FRIEND = MOBILE / ".friend-access.txt"


def owner_keys(shared_home: str) -> dict[str, str]:
    if shared_home:
        home = Path(shared_home).expanduser().resolve()
        values = {name: sharekeys.granted(name, where=home) for name in sharekeys.SHARED_PROVIDERS}
        if all(values.values()):
            return values
        raise SystemExit(
            f"No complete shared grant in {home}. Point --shared-home at the "
            "folder that holds .kriko/shared.json and .kriko/device.key."
        )
    try:
        return {name: keys.require(name) for name in sharekeys.SHARED_PROVIDERS}
    except Exception as error:  # noqa: BLE001 — the sentence is the point
        raise SystemExit(
            f"No owner keys on this machine ({error}). Set --shared-home, or put "
            "MERCURY_API_KEY and DEEPSEEK_API_KEY in ~/.kriko/env."
        ) from error


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--shared-home",
        default="",
        help="a Kriko home whose shared.json already holds the owner's grant",
    )
    parser.add_argument("--password", default="", help="the password friends will be given")
    parser.add_argument("--questions", type=int, default=10, help="trial questions per install")
    parser.add_argument("--label", default="Kriko Agent", help="label carried on the grant")
    parser.add_argument("--no-code", action="store_true", help="bake only the trial")
    args = parser.parse_args()

    pepper = sharekeys.pepper().decode("utf-8")
    if not pepper:
        raise SystemExit(
            "This checkout has no share pepper. Run tools/make_share_pepper.py "
            "first; a build without one offers no trial and opens no code."
        )

    values = owner_keys(args.shared_home)
    trial = sharekeys.make_trial(values, questions=max(1, min(999, args.questions)))
    if not sharekeys.trial_keys(trial):
        raise SystemExit("The trial bundle the app just made does not open in this build.")

    body = "\n".join(
        [
            "// Generated by kriko-mobile/tools/make-secrets.py — not source, not committed.",
            "// The pepper binds an access code to this app; the bundle is the app's",
            "// own keys, sealed. Both are credentials. Re-run the tool to rotate.",
            "",
            f"export const PEPPER = {json.dumps(pepper)};",
            f"export const TRIAL_BUNDLE = {json.dumps(trial)};",
            f"export const TRIAL_QUESTIONS = {max(1, min(999, args.questions))};",
            "",
        ]
    )
    SECRETS.write_text(body, encoding="utf-8")

    print(f"pepper + trial written to {SECRETS.relative_to(ROOT)}")
    print(f"trial: {args.questions} question(s), opens in this build")

    if args.no_code:
        return
    password = args.password or secrets.token_urlsafe(9)
    if len(password) < 8:
        raise SystemExit("The password must be at least 8 characters.")
    code = sharekeys.make_access(password, values)
    if sharekeys.open_access(code, password) != values:
        raise SystemExit("The access code the app just made does not open. Refusing to write it.")

    FRIEND.write_text(
        "Kriko Agent — access for friends\n"
        f"label: {args.label}\n"
        f"password: {password}\n"
        f"code: {code}\n\n"
        "Send the code and the password in two separate messages. Anyone with both\n"
        "can spend these keys inside Kriko until the owner rotates them.\n",
        encoding="utf-8",
    )
    print(f"friend access written to {FRIEND.relative_to(ROOT)}")
    print(f"password: {password}")
    print(f"code: {code}")


if __name__ == "__main__":
    main()
