#!/usr/bin/env python3
"""Make this build's share pepper, or show the one it has.

The pepper is what makes a shared access code *"not work outside kriko app"*
(`src/app/sharekeys.py`): the password is derived together with it, so a code
and its password open nothing in a build that lacks it — a script, a browser, a
different program. It is a credential, so it is written to
`src/app/sharekeys_pepper.py`, which is gitignored, and it must be present when
`kriko-ui/package.ps1` freezes the sidecar.

    python tools/make_share_pepper.py --show          # is this build bound?
    python tools/make_share_pepper.py                 # make one, if none is here
    python tools/make_share_pepper.py --rotate        # replace it (codes stop opening)

Rotating is a real decision: every access code handed out with the old pepper
stops opening in the new build, and the trial bundle baked with it must be made
again (`tools/make_trial_access.py`). Rotate when a pepper has leaked, not
between releases.
"""

from __future__ import annotations

import argparse
import re
import secrets
import sys
from pathlib import Path

TARGET = Path(__file__).resolve().parent.parent / "src" / "app" / "sharekeys_pepper.py"
#: The shape `packaging/configure_share_pepper.py` accepts and writes. The two
#: tools answer "is this build bound?" about the same file, so they must mean the
#: same thing by a pepper: 32 bytes, hex.
VALID = re.compile(r"^[0-9a-fA-F]{64}$")

TEMPLATE = '''"""This build's share pepper. Generated by tools/make_share_pepper.py.

Not source, not committed (`.gitignore`), and a credential: it is what binds a
shared access code to this application rather than to the password alone.
"""

PEPPER = "{pepper}"
'''


def current() -> str:
    """The pepper in this build's module, or "" when there is no usable one.

    A `PEPPER` line of the wrong shape is not a pepper: `sharekeys.bound()` would
    call the build bound and every code sealed here would then be sealed under
    something the packaging step refuses. Both tools read this one function's
    rule, so the packaging helper and this one cannot disagree.
    """
    if not TARGET.exists():
        return ""
    for line in TARGET.read_text(encoding="utf-8").splitlines():
        if line.startswith("PEPPER"):
            value = line.partition("=")[2].strip().strip('"').strip("'")
            return value if VALID.fullmatch(value) else ""
    return ""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--show", action="store_true", help="print whether this build is bound")
    parser.add_argument("--rotate", action="store_true", help="replace an existing pepper")
    args = parser.parse_args(argv)

    here = current()
    if args.show:
        print(f"{TARGET}: {'a pepper is here' if here else 'no pepper — this build is not bound'}")
        return 0
    if here and not args.rotate:
        print(f"{TARGET} already holds a pepper; --rotate replaces it and stops old codes opening.")
        return 0
    TARGET.write_text(TEMPLATE.format(pepper=secrets.token_hex(32)), encoding="utf-8")
    print(f"wrote {TARGET} (gitignored); a code sealed before this no longer opens.")
    print("Make the trial bundle for this build next: python tools/make_trial_access.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
