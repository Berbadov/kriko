"""The cases, and the one brief every candidate is given.

The corpus is the versioned controlled set that already ships with the app
(`benchprecision.json`, generated by `app/precisioncases.py`). It is the right
instrument for this question and it was not being used as one: ten fictional
products, each with a document that is the *entire* world of the case, an
answer key that never appears in the prompt, and one named measurement
dimension apiece — a revision that a nearby revision must not be confused with,
a market, an excluded build year, a superseded bulletin, a missing identity, 32
distractors around one true line, a case with no evidence at all, and a
consumable blamed for its host's fault.

Three properties make it a fair comparison, and this module is where they are
enforced rather than assumed:

**One prompt.** `prompt(case)` is the only way a case becomes text, and it is
built from the case and nothing else — no reader preference, no installed pack,
no model-specific hint. Two candidates that saw different text were not
compared, so `prompt_fingerprint(case)` is recorded with every run and the
report prints it: a table whose fingerprints disagree is a table to throw away.

**No network.** The documents are supplied in the brief. A candidate cannot
search, so a case measures what the model does with evidence, never how good
its search luck was. This is also why the suite is repeatable: the world does
not change between two runs.

**The answer key stays out.** `supported`, `expected_specs` and
`expect_abstention` are what `metrics.py` grades against; nothing in `prompt`
reads them. A brief that leaked its own key would measure how well a model
copies.
"""

import hashlib

#: The suite this module runs. `precision` is the controlled corpus; `web` is
#: the legacy live-search suite, which this engine deliberately does not run —
#: a case whose documents change between two runs cannot support a token
#: comparison. Named here so the refusal is visible rather than silent.
SUITE = "precision"

#: The heading the brief uses for supplied documents. The models are told to
#: read the pages "below"; this is that below, and it is one string so the
#: fingerprint cannot drift from what the model actually saw.
DOCUMENTS_HEADING = "## Supplied documents"


def load(suite: str = SUITE) -> list[dict]:
    """Every case in the corpus, in file order.

    In file order because the set is versioned and a stable order is part of
    what the version promises: "the first three cases" is the same three on
    every machine and in every report.
    """
    from app import benchcases

    if suite != SUITE:
        raise ValueError(
            f"the model benchmark runs the {SUITE!r} corpus only — {suite!r} "
            "is the legacy live-web suite, whose documents change between runs"
        )
    return benchcases.load(suite)


def identity(suite: str = SUITE) -> dict:
    """`set_id` and `set_version` for the corpus, for stamping a run.

    A number without the set it was measured on is folklore. This is the set.
    """
    found = load(suite)
    if not found:
        return {"set_id": "", "set_version": "", "cases": 0}
    return {
        "set_id": str(found[0].get("set_id") or ""),
        "set_version": str(found[0].get("set_version") or ""),
        "cases": len(found),
    }


def documents(case: dict) -> dict[str, str]:
    """`{url: text}` — what `metrics.py` checks a quote against.

    The same mapping the prompt is built from, by construction: a quote is
    checked against the exact bytes the model was shown.
    """
    return {
        str(one.get("url") or ""): str(one.get("text") or "")
        for one in (case.get("documents") or [])
        if isinstance(one, dict)
    }


def prompt(case: dict) -> str:
    """The brief: instructions, then every document, then nothing else.

    Built from `app.precisionbench.brief` — the same instructions the controlled
    suite already used — plus the documents. The documents are appended here for
    *every* candidate including the local one, which the old benchmark did not
    do: there, a local model received its evidence through a different channel
    than a hosted one, so the two were never quite given the same task.

    No `temperature`, no `max_tokens`, no model name is in this string. A brief
    that knew which model was reading it could not compare two of them.
    """
    from app import precisionbench

    task = precisionbench.brief(case)
    supplied = documents(case)
    if supplied:
        task += "\n" + DOCUMENTS_HEADING + "\n" + "\n\n".join(
            f"### URL: {url}\n\n{text}" for url, text in supplied.items()
        )
    return task


def prompt_fingerprint(case: dict) -> str:
    """The first twelve hex of the brief's SHA-256.

    Twelve because it is meant to be *read* in a table, not verified by a
    cryptographer: two runs agreeing on twelve hex digits agree on the whole
    prompt with a probability no reader has to think about.
    """
    return hashlib.sha256(prompt(case).encode("utf-8")).hexdigest()[:12]


def answer_key(case: dict) -> dict:
    """What a competent answer looks like, for a reader checking the report.

    Not used by the scorer — `metrics.py` reads the case itself — but printed
    beside a failure so a person can tell "the model missed this" from "the key
    is wrong", which is the difference between a model problem and a corpus bug.
    """
    return {
        "must_find": [one.get("id") or one.get("claim") or one.get("title") or ""
                      for one in (case.get("supported") or case.get("must_find") or [])],
        "must_not_claim": [one.get("claim") or "" for one in (case.get("must_not_find") or [])],
        "known_absent": [str(one) for one in (case.get("known_absent") or [])],
        "specs": [f'{one.get("name")} = {one.get("value")}'
                  for one in (case.get("expected_specs") or [])],
        "expect_abstention": bool(case.get("expect_abstention")),
        "documents": len(case.get("documents") or []),
    }


def problems(cases: list[dict]) -> list[str]:
    """Corpus defects that would make a score a lie, as sentences.

    Run before a sweep rather than trusted: an empty `supported` list on a case
    that is not marked as expecting abstention is an answer key nobody can hit,
    and every candidate would score zero recall for a reason that has nothing to
    do with the candidate. A benchmark that cannot tell that from a bad model is
    worse than no benchmark.
    """
    found: list[str] = []
    for case in cases:
        name = str(case.get("id") or "?")
        if not case.get("documents"):
            found.append(f"{name}: no documents, so there is nothing to answer from")
        if not (case.get("supported") or case.get("expected_specs")) \
                and not case.get("expect_abstention"):
            found.append(
                f"{name}: no supported facts and not marked as expecting "
                "abstention, so recall is unhittable"
            )
        for entry in case.get("supported") or []:
            if not str(entry.get("quote") or "").strip():
                found.append(f"{name}: a supported fact carries no quote")
            if not str(entry.get("url") or "").strip():
                found.append(f"{name}: a supported fact carries no url")
    return found
