"""Forgetting a saved check is reversible for as long as the reader can see it.

The reader's options were "Are you sure? Delete / Keep" and then nothing. A
check is an answer they spent an agent's time on, and the confirm dialog is the
wrong instrument for it: they have already said yes, and what they need is the
next few seconds in which they can say "not that one".

So the delete hands back what it took (`state.delete_lookup` returns the row and
its triage), the interface keeps it for the life of the panel, and
`POST /api/history/restore` puts it back verbatim. No trash table, because a
trash table is a second lifetime to get wrong.

The one thing the undo must not do is *overwrite*: if the same id has been
saved again since, the newer answer is the one the reader means.
"""

import pytest
from fastapi.testclient import TestClient

from app.web import state
from app.web.app import create_app
from app.web.settings import Settings


@pytest.fixture
def app_state(tmp_path):
    connection = state.connect(tmp_path / "app.sqlite")
    yield connection
    connection.close()


@pytest.fixture
def client(tmp_path, app_state):
    return TestClient(create_app(Settings(store_path=tmp_path / "store.sqlite",
                                          app_state_path=tmp_path / "app.sqlite")))


def _saved(app_state, label="VW Golf 1.6 TDI"):
    lookup_id = state.record_lookup(
        app_state, source="extension", label=label,
        request={"url": "https://x.test/1"},
        response={"claims": [{"title": "Timing chain"}]},
    )
    # Written directly because nothing in the app writes `claim_checks`: the
    # table and its `claim_notes` sibling have a schema, a delete, and no
    # insert anywhere (`state.mark_claim` is a different table). That is its own
    # finding — see the sweep note on dead tables — but the undo has to preserve
    # whatever is there, and a row that exists has to survive the round trip.
    app_state.execute(
        "INSERT INTO claim_checks (lookup_id, claim_key, created_at)"
        " VALUES (?,?,?)", (lookup_id, "timing chain", "2026-10-18T10:00:00"))
    app_state.commit()
    return lookup_id


def test_the_delete_hands_back_what_it_took(app_state, client):
    lookup_id = _saved(app_state)
    body = client.delete(f"/api/history/{lookup_id}").json()
    assert body["deleted"] is True
    assert body["undo"]["lookup"]["lookup_id"] == lookup_id
    assert body["undo"]["lookup"]["label"] == "VW Golf 1.6 TDI"
    assert [one["claim_key"] for one in body["undo"]["checks"]] == ["timing chain"]


def test_the_undo_puts_the_check_and_its_triage_back(app_state, client):
    lookup_id = _saved(app_state)
    undo = client.delete(f"/api/history/{lookup_id}").json()["undo"]
    assert client.get("/api/history").json()["items"] == []

    restored = client.post("/api/history/restore", json=undo)
    assert restored.status_code == 200
    assert restored.json()["lookup_id"] == lookup_id

    items = client.get("/api/history").json()["items"]
    assert [one["lookup_id"] for one in items] == [lookup_id]
    assert state.get_lookup(app_state, lookup_id)["response"] == {
        "claims": [{"title": "Timing chain"}]}
    kept = [row["claim_key"] for row in app_state.execute(
        "SELECT claim_key FROM claim_checks WHERE lookup_id = ?", (lookup_id,))]
    assert kept == ["timing chain"], "the triage came back with the answer"


def test_the_undo_will_not_overwrite_a_newer_answer(app_state, client):
    """If the id is in use again, the newer check is the one the reader means."""
    lookup_id = _saved(app_state)
    undo = client.delete(f"/api/history/{lookup_id}").json()["undo"]
    # The id is generated by `record_lookup`, so a "newer answer" is modelled
    # the way the engine models one: the row written back under the same id.
    app_state.execute(
        "INSERT INTO lookups (lookup_id, created_at, source, label,"
        " request_json, response_json) VALUES (?,?,?,?,?,?)",
        (lookup_id, "2026-10-19T00:00:00", "app", "The newer one", "{}", "{}"),
    )
    app_state.commit()

    answer = client.post("/api/history/restore", json=undo)
    assert answer.status_code == 409
    assert state.get_lookup(app_state, lookup_id)["label"] == "The newer one"


def test_a_record_with_no_lookup_id_is_refused(app_state, client):
    answer = client.post("/api/history/restore", json={"lookup": {}, "checks": []})
    assert answer.status_code == 409


def test_forgetting_something_that_is_not_there_is_still_a_404(client):
    assert client.delete("/api/history/nope").status_code == 404
